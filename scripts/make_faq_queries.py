"""Generate the `official_faq` query slice from FAQ headings in the indexed corpus.

The query text is the FAQ question exactly as the Python / PyTorch maintainers wrote it, and the
relevant section is the section that answers it. Nothing here is authored by us: only the *choice*
of which questions to include (substantive answers, not link-only stubs) is ours.

    uv run python scripts/make_faq_queries.py
"""

from pathlib import Path

import yaml

from neural_debugger.data.corpus import load_corpus

PY = "python/3.12/faq/"
PT = "pytorch/2.14/notes/faq#"
PYTHON_FAQ = (
    [
        PY + "programming#" + a
        for a in [
            "why-am-i-getting-an-unboundlocalerror-when-the-variable-has-a-value",
            "why-did-changing-list-y-also-change-list-x",
            "why-are-default-values-shared-between-objects",
            "why-do-lambdas-defined-in-a-loop-with-different-values-all-return-the-same-result",
            "how-do-i-share-global-variables-across-modules",
            "how-can-i-have-modules-that-mutually-import-each-other",
            "when-i-edit-an-imported-module-and-reimport-it-the-changes-don-t-show-up-why-does-this-happen",
            "how-do-i-convert-a-string-to-a-number",
            "what-is-the-most-efficient-way-to-concatenate-many-strings-together",
            "how-do-i-create-a-multidimensional-list",
            "why-does-a-tuple-i-item-raise-an-exception-when-the-addition-works",
            "my-class-defines-del-but-it-is-not-called-when-i-delete-the-object",
            "what-are-the-rules-for-local-and-global-variables-in-python",
            "i-try-to-use-spam-and-i-get-an-error-about-someclassname-spam",
            "how-can-i-sort-one-list-by-values-from-another-list",
            "my-program-is-too-slow-how-do-i-speed-it-up",
        ]
    ]
    + [
        PY + "library#" + a
        for a in [
            "how-do-i-generate-random-numbers-in-python",
            "none-of-my-threads-seem-to-run-why",
            "what-kinds-of-global-value-mutation-are-thread-safe",
            "how-do-i-parcel-out-work-among-a-bunch-of-worker-threads",
            "how-do-i-make-a-python-script-executable-on-unix",
        ]
    ]
    + [
        PY + "design#" + a
        for a in [
            "why-are-floating-point-calculations-so-inaccurate",
            "why-are-python-strings-immutable",
            "why-doesn-t-list-sort-return-the-sorted-list",
            "why-must-self-be-used-explicitly-in-method-definitions-and-calls",
            "why-is-join-a-string-method-instead-of-a-list-or-tuple-method",
            "why-isn-t-there-a-switch-or-case-statement-in-python",
            "why-must-dictionary-keys-be-immutable",
        ]
    ]
)
PYTORCH_FAQ = [
    PT + a
    for a in [
        "my-data-loader-workers-return-identical-random-numbers",
        "my-gpu-memory-isn-t-freed-properly",
        "my-model-reports-cuda-runtime-error-2-out-of-memory",
        "my-out-of-memory-exception-handler-can-t-allocate-memory",
        "my-recurrent-network-doesn-t-work-with-data-parallelism",
    ]
]


def build(
    prefix: str, short: str, sections: list[str], corpus_prefix: str
) -> list[dict[str, object]]:
    corpus = load_corpus(Path("data/corpus"))
    rows = []
    for i, sid in enumerate(sections, start=1):
        assert sid in corpus.section_ids, sid
        heading = corpus.section_heading_path(sid)[-1]
        rows.append(
            {
                "id": f"{prefix}{i:03d}",
                "query": heading,
                "slice": "official_faq",
                "relevant": [short + sid[len(corpus_prefix) :]],
            }
        )
    return rows


if __name__ == "__main__":
    out = Path("data/eval")
    py_rows = build("pyfaq", "py:", PYTHON_FAQ, "python/3.12/")
    pt_rows = build("ptfaq", "pt:", PYTORCH_FAQ, "pytorch/2.14/")
    header = (
        "# Generated by scripts/make_faq_queries.py: query text = official FAQ heading, verbatim.\n"
    )
    (out / "queries_faq_python.yaml").write_text(
        header + yaml.safe_dump(py_rows, sort_keys=False, allow_unicode=True, width=200)
    )
    (out / "queries_faq_pytorch.yaml").write_text(
        header + yaml.safe_dump(pt_rows, sort_keys=False, allow_unicode=True, width=200)
    )
    print(len(py_rows), "python FAQ queries,", len(pt_rows), "pytorch FAQ queries")
